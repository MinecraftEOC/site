/** Ответ игрового сервера на status-пинг — только те поля, которые нужны сайту. */
export interface IMinecraftStatus {
    /** Блок версии сервера. */
    version?: {
        /** Человекочитаемое имя версии/ядра. */
        name?: string;
        /** Номер протокола. */
        protocol?: number;
    };
    /** Блок игроков. */
    players?: {
        /** Игроков в сети. */
        online?: number;
        /** Всего слотов. */
        max?: number;
        /** Выборка игроков онлайн — сервер отдаёт не более 12. */
        sample?: {
            /** Ник игрока. */
            name: string;
            /** UUID игрока. */
            id: string;
        }[];
    };
}
