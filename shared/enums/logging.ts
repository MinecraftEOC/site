/** Категория серверных журналов на диске. */
export enum ELogCategory {
    /** Ошибки всех категорий (`ERROR`). */
    Errors = 'errors',
    /** Системные события и жизненный цикл скриптов. */
    System = 'system',
    /** Операции со стейтами игроков и мира. */
    States = 'states',
    /** Расчёт и применение урона, ранений и смерти. */
    Damage = 'damage',
    /** Проверки и операции взлома замков. */
    Locks = 'locks',
    /** Внешние HTTP-запросы и интеграции. */
    Api = 'api',
    /** Проверки параметров и навыков персонажей. */
    Checks = 'checks',
    /** Пошаговые журналы отдельных боёв. */
    Combat = 'combat',
}

/** Уровень важности записи журнала. */
export enum ELogLevel {
    /** Ошибка выполнения или сбой операции. */
    Error = 'ERROR',
    /** Предупреждение или нештатная ситуация. */
    Warn = 'WARN',
    /** Штатное информационное событие. */
    Info = 'INFO',
    /** Отладочная подробность. */
    Debug = 'DEBUG',
}

/** Направление сортировки записей при чтении файла журнала. */
export enum ELogOrder {
    /** Сначала новые записи (чтение с конца файла). */
    Desc = 'desc',
    /** Сначала старые записи (чтение с начала файла). */
    Asc = 'asc',
}

